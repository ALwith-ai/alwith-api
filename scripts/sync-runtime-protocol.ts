import { resolve } from "node:path"

const binary = process.argv[2]
if (!binary) throw new Error("Usage: bun scripts/sync-runtime-protocol.ts <runtime-binary> [--check]")
const child = Bun.spawn([resolve(binary), "--export-protocol", "rust"], { stdout: "pipe", stderr: "inherit" })
const source = await new Response(child.stdout).text()
if ((await child.exited) !== 0) throw new Error("Runtime protocol export failed")
if (!source.includes("pub enum RuntimeEvent")) throw new Error("Invalid Runtime protocol export")
const generated = "// Generated by sync-runtime-protocol.ts from the Runtime binary; do not edit.\n" + source
const target = Bun.file(resolve(import.meta.dirname, "../crates/api/src/protocol.rs"))
if (process.argv[3] === "--check") {
  if ((await target.text()) !== generated) throw new Error("Runtime/client protocol snapshot drift")
} else {
  await Bun.write(target, generated)
}
